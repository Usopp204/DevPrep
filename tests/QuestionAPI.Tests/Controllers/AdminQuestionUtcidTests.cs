 private static async Task List(string kind,int n){var(c,s,_)=New();var q=new AdminQuestionQueryDto{Keyword=n==3?"async":null,Status=n==5?"Deleted":null,PageIndex=n==4?int.MaxValue:1,PageSize=n==4?1:10};var page=new AdminPagedResultDto<AdminQuestionListItemDto>{PageIndex=q.PageIndex,PageSize=q.PageSize,TotalRecords=n==2?0:1};if(n==6){if(kind=="list")s.Setup(x=>x.GetAsync(q)).ThrowsAsync(new Exception("db"));else if(kind=="search")s.Setup(x=>x.SearchAsync(q)).ThrowsAsync(new Exception("db"));else s.Setup(x=>x.FilterAsync(q)).ThrowsAsync(new Exception("db"));}else{if(kind=="list")s.Setup(x=>x.GetAsync(q)).ReturnsAsync(page);else if(kind=="search")s.Setup(x=>x.SearchAsync(q)).ReturnsAsync(page);else s.Setup(x=>x.FilterAsync(q)).ReturnsAsync(page);}var r=kind=="list"?await c.Get(q):kind=="search"?await c.Search(q):await c.Filter(q);Assert.Equal(n==6?500:200,Assert.IsAssignableFrom<ObjectResult>(r).StatusCode);}
 private static async Task Detail(int n){var(c,s,_)=New();var id=n==3?Guid.Empty:n==4?Guid.Parse("ffffffff-ffff-ffff-ffff-ffffffffffff"):Guid.NewGuid();if(n==6){s.Setup(x=>x.GetDetailAsync(id)).ThrowsAsync(new InvalidOperationException("db"));await Assert.ThrowsAsync<InvalidOperationException>(()=>c.Detail(id));return;}s.Setup(x=>x.GetDetailAsync(id)).ReturnsAsync(n==2?null:new AdminQuestionDetailDto{QuestionId=id,Question="Q",IsDeleted=n==5});var r=await c.Detail(id);Assert.Equal(n==2?404:200,Assert.IsAssignableFrom<ObjectResult>(r).StatusCode);}
 private static AdminCreateQuestionDto CreateDto(int n)=>new(){CategoryId=Guid.NewGuid(),Question=n==5?new string('Q',10000):"Question",Difficulty="Medium",Answer="Answer",Status="Active"};
 private static async Task Create(int n){var(c,s,a)=New(n!=2);var q=CreateDto(n);if(n==3)q.Question="";if(n is 3 or 4 or 6)s.Setup(x=>x.CreateAsync(q,n==2?null:a)).ThrowsAsync(new InvalidOperationException(n==4?"duplicate":"failure"));else s.Setup(x=>x.CreateAsync(q,n==2?null:a)).ReturnsAsync(new AdminQuestionDetailDto{QuestionId=Guid.NewGuid(),Question=q.Question});var r=await c.Create(q);Assert.Equal(n is 3 or 4 or 6?400:200,Assert.IsAssignableFrom<ObjectResult>(r).StatusCode);}
 private static async Task Update(int n){var(c,s,a)=New(n!=6);var id=n==4?Guid.Empty:n==5?Guid.Parse("ffffffff-ffff-ffff-ffff-ffffffffffff"):Guid.NewGuid();var q=new AdminUpdateQuestionDto{Question="Updated"};if(n==3)s.Setup(x=>x.UpdateAsync(id,q,a)).ThrowsAsync(new InvalidOperationException("invalid"));else s.Setup(x=>x.UpdateAsync(id,q,n==6?null:a)).ReturnsAsync(n==2?null:new AdminQuestionDetailDto{QuestionId=id,Question=q.Question});var r=await c.Update(id,q);Assert.Equal(n==2?404:n==3?400:200,Assert.IsAssignableFrom<ObjectResult>(r).StatusCode);}
 private static async Task Delete(int n){var(c,s,a)=New(n!=6);var id=n==4?Guid.Empty:n==5?Guid.Parse("ffffffff-ffff-ffff-ffff-ffffffffffff"):Guid.NewGuid();if(n==3)s.Setup(x=>x.DeleteAsync(id,a)).ThrowsAsync(new Exception("db"));else s.Setup(x=>x.DeleteAsync(id,n==6?null:a)).ReturnsAsync(n!=2);var r=await c.Delete(id);Assert.Equal(n==2?404:n==3?400:200,Assert.IsAssignableFrom<ObjectResult>(r).StatusCode);}
